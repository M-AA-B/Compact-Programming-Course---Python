# Simple Variable Declaration and Output

def main():
    zahl = 10
    kommazahl = 10.5
    text = "Hello, World!"
    wahrheitswert = True
    
    print(f"{zahl} is a {type(zahl)}")
    print(f"{kommazahl} is a {type(kommazahl)}")
    print(f"{text} is a {type(text)}")
    print(f"{wahrheitswert} is a {type(wahrheitswert)}")

main()
