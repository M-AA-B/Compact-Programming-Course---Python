# Data Type Conversion

def main():
    integer = 5
    float_number = 5.5
    string = "10"
    print(f"integer = {integer}")
    print(f"float_number = {float_number}")
    print(f"string = {string}")
    print(f"1. integer {integer} to floating-point number = {float(integer)}")
    print(f"2. float_number {float_number} to an integer = {int(float_number)}")
    print(f"3. integer {integer} to string = {str(integer)}")
    print(f"4. string {string} to integer = {int(string)}")
    print(f"5. integer {integer} to boolean = {bool(integer)}")
    
main()
