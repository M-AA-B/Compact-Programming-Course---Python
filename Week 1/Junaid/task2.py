# program that stores an integer, a floating-point number, a string, and a boolean
# variable, and then outputs them

zahl = 10
print("type of zahl", type(zahl))

kommazahl = 10.5
print("type of kommazahl", type(kommazahl))

text = "Hello, World!"
print("type of text", type(text))

wahrheitswert = True
print("type of wahrheitswert", type(wahrheitswert))

print("Integer:", zahl)
print("Floating-point number:", kommazahl)
print("String:", text)
print("Boolean:", wahrheitswert)